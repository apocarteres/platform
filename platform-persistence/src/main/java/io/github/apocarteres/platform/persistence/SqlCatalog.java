package io.github.apocarteres.platform.persistence;

/**
 * Неизменяемый набор SQL-запросов одного каталога ресурсов.
 *
 * <p>Запросы хранятся в файлах, а не строками в коде: один файл — один
 * запрос, имя файла совпадает с именем в {@link #get(String)}. Так план
 * запроса виден целиком в одном месте, а не собирается из фрагментов
 * доменного кода.
 */
public interface SqlCatalog {

  /**
   * Возвращает запрос по имени.
   *
   * @throws IllegalArgumentException если запрос с таким именем не объявлен;
   *         опечатка в имени обязана обнаруживаться сразу, а не выражаться
   *         в {@code null} и последующем непонятном отказе драйвера
   */
  String get(String name);
}
